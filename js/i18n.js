let currentLang = "zh";

export function getLang() {
  return currentLang;
}

export function t(key, vars = {}) {
  let text = copy[currentLang][key] ?? copy.zh[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replace(`{${name}}`, String(value));
  }
  return text;
}

function detectLang() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "zh" || saved === "en") return saved;
  const browser = navigator.language?.toLowerCase() ?? "";
  return browser.startsWith("zh") ? "zh" : "en";
}

function applyStaticCopy() {
  document.documentElement.lang = currentLang === "en" ? "en" : "zh-Hant";
  document.title = t("page.title");

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = t("page.metaDesc");

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const ui = node.closest("[data-viewer-ui]");
    if (node.matches("[data-status]") && ui?.classList.contains("is-ready")) return;
    node.textContent = t(node.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    const [attr, key] = node.dataset.i18nAttr.split(":");
    node.setAttribute(attr, t(key));
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const on = button.dataset.lang === currentLang;
    button.classList.toggle("is-on", on);
    button.setAttribute("aria-pressed", String(on));
  });
}

export function setLang(lang) {
  if (lang !== "zh" && lang !== "en") return;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  applyStaticCopy();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

export function initI18n() {
  currentLang = detectLang();
  applyStaticCopy();

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => setLang(button.dataset.lang));
  });
}
